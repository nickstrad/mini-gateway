package catalog

import (
	"bytes"
	"fmt"
	"strings"

	"github.com/nickstrad/mini-gateway/internal/obs"
	"github.com/nickstrad/mini-gateway/internal/obs/csvflush"
	"github.com/nickstrad/mini-gateway/internal/obs/simsrc"
)

const DocPath = "docs/csv-schema.md"

func Registry() (*obs.Registry, error) {
	var reg obs.Registry
	if err := reg.Declare(obs.ComponentObs, obs.SelfMetrics()...); err != nil {
		return nil, err
	}
	for _, d := range simsrc.All() {
		if err := reg.Declare(d.Component, d.Metrics...); err != nil {
			return nil, err
		}
	}
	return &reg, nil
}

func labels(s obs.LabelSet) string {
	n := s.Names()
	if len(n) == 0 {
		return "—"
	}
	return strings.Join(n, ", ")
}

func cell(s string) string { return strings.ReplaceAll(s, "|", `\|`) }

func columns(b *bytes.Buffer, title string, cs []csvflush.Column) {
	fmt.Fprintf(b, "### `%s`\n\n| # | Column | Type | Meaning |\n| --- | --- | --- | --- |\n", title)
	for i, c := range cs {
		fmt.Fprintf(b, "| %d | `%s` | %s | %s |\n", i+1, c.Name, c.Type, cell(c.Meaning))
	}
	b.WriteString("\n")
}

func Markdown() ([]byte, error) {
	reg, err := Registry()
	if err != nil {
		return nil, err
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "# CSV flush schema, version %d\n\n", csvflush.SchemaVersion)
	b.WriteString("GENERATED by `scripts/gen-docs.sh` from `internal/obs/catalog`; do not edit by hand. ")
	b.WriteString("`internal/obs/catalog` holds a test that fails when this file differs from the code.\n\n")
	b.WriteString("## Run directories\n\n")
	b.WriteString("One run is one directory `<obs.csv.dir>/<run_id>/` with three files. Simulator runs use the run id ")
	b.WriteString("`<scenario>/<seed>/<arm>`, so a root holds `<root>/<scenario>/<seed>/<arm>/`. ")
	b.WriteString("`metrics.csv` and `histograms.csv` get rows appended at every flush, sorted by (`flush_seq`, `instance`, `component`, `metric`, labels); ")
	b.WriteString("`run.csv` is written last, at close. A directory without `run.csv` did not finish.\n\n")
	b.WriteString("## Columns\n\n")
	columns(&b, csvflush.MetricsFile, csvflush.MetricsColumns())
	columns(&b, csvflush.HistogramsFile, csvflush.HistogramsColumns())
	columns(&b, csvflush.RunFile, csvflush.RunColumns())
	b.WriteString("## Metric registry\n\n")
	b.WriteString("Every metric a component may export. Kind `histogram` rows go to `histograms.csv`; the others to `metrics.csv`. ")
	b.WriteString("Merge is how values from several instances combine: `sum`, or `max` for high-water marks; histograms merge by bucket.\n\n")
	b.WriteString("| Component | Metric | Kind | Labels | Unit | Merge | Help |\n| --- | --- | --- | --- | --- | --- | --- |\n")
	for _, d := range reg.All() {
		merge := d.Merge.String()
		if d.Kind == obs.KindHistogram {
			merge = "by bucket"
		}
		fmt.Fprintf(&b, "| `%s` | `%s` | %s | %s | %s | %s | %s |\n", d.Component, d.Name, d.Kind, labels(d.Labels), d.Unit, merge, cell(d.Help))
	}
	return b.Bytes(), nil
}
