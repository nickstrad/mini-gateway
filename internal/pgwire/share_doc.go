package pgwire

import (
	"strconv"
	"strings"
)

func SafeShapeMarkdown() string {
	var b strings.Builder
	b.WriteString("# The safe shape\n\n")
	b.WriteString("Generated by `scripts/gen-docs.sh` from `internal/pgwire/share.go`. Do not edit by hand: a test fails when this file differs from the code.\n\n")
	b.WriteString("A `Query` text fits the safe shape when all of the rules below hold. Only then is it `SafeRead` (a read for the error contract: `08006` rather than `08007` after a lost connection) and, outside a transaction and not rejected, `Shareable` (shared by `coalesce: auto`). The check reads the raw bytes; it uses neither the lexer nor the reject classifier. Anything it does not list does not fit.\n\n")
	b.WriteString("## Rules\n\n")
	rules := []string{
		"The text is 1 to " + strconv.Itoa(ShareMaxLen) + " bytes long.",
		"Every byte is an ASCII letter, an ASCII digit, or one of " + shareDocBytes() + ". No tab, line break, dot, semicolon, backslash, dollar sign, double quote, minus, slash, colon, plus, percent or non-ASCII byte.",
		"Toggling in and out of a string at every `'` (so `''` toggles twice), the text ends outside a string.",
		"The byte before every opening `'` is not a letter, a digit or `_` (no `E'...'`, `B'...'`, `X'...'`, `N'...'`).",
		"No string, lower-cased, contains " + shareDocWords(ShareTimeWords) + " (Postgres's relative-time input words; a substring match).",
		"Outside strings, the first word is `" + ShareLead + "` (any case) and nothing but spaces comes before it. A word is a maximal run of letters, digits and `_`.",
		"Outside strings, no word is on the stop list.",
		"Outside strings, every word followed (after optional spaces) by `(` is on the parenthesis-keyword list or on the share allow-list.",
	}
	for i, r := range rules {
		b.WriteString(strconv.Itoa(i+1) + ". " + r + "\n")
	}
	b.WriteString("\nWords are compared ASCII case-insensitively.\n\n")
	b.WriteString("## Stop list\n\n" + shareDocWords(ShareStopWords) + "\n\n")
	b.WriteString("## Parenthesis keywords\n\nWords that may precede `(` without being a function call. Each is a reserved or column-name keyword in PostgreSQL 17, which no unqualified function call can use as its name.\n\n" + shareDocWords(ShareParenKeywords) + "\n\n")
	b.WriteString("## Share allow-list\n\nFunctions with no side effect and no per-call or per-session result.\n\n" + shareDocWords(ShareAllowList) + "\n\n")
	b.WriteString("## Hint\n\nA text that begins with the exact bytes `" + ShareHint + "` is reported as `Hinted`. The hint never makes a text `SafeRead` or `Shareable`; in `hinted` mode the coalescer shares on the mark alone.\n")
	return b.String()
}

func shareDocWords(list []string) string {
	parts := make([]string, len(list))
	for i, w := range list {
		parts[i] = "`" + w + "`"
	}
	return strings.Join(parts, ", ")
}

func shareDocBytes() string {
	var parts []string
	for i := 0; i < len(shareAlphabetPunct); i++ {
		c := shareAlphabetPunct[i]
		if c == ' ' {
			parts = append(parts, "the space (0x20)")
			continue
		}
		parts = append(parts, "`"+string(c)+"`")
	}
	return strings.Join(parts, " ")
}
