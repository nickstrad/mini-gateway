package pgwire

import (
	"strconv"
	"strings"
)

// ErrorRowsMarkdown renders docs/error-contract.md directly from ErrorRows so
// the published error contract cannot drift from the wire builders.
func ErrorRowsMarkdown() string {
	var b strings.Builder
	b.WriteString("# Error contract\n\n")
	b.WriteString("Generated by `scripts/gen-docs.sh` from `internal/pgwire/errors.go` (the table `ErrorRows`). Do not edit by hand: a test fails when this file differs from the code.\n\n")
	b.WriteString("Every reply the proxy makes itself is an `ErrorResponse` with the severity, SQLSTATE and message below and a detail line `" + ReplyDetailPrefix + "<row id>`, followed by the end marker the row names. `ERROR` rows end with `ReadyForQuery` carrying the status byte the client believes (`I` outside a transaction; inside one, the current status). `FATAL` rows have no end marker and the client connection is closed. The extended-protocol row discards messages until `Sync` and then sends `ReadyForQuery`. Each proxy-made reply is counted under its counter key.\n\n")
	b.WriteString("| Row id | Situation | Reply | SQLSTATE | Message | Reached the database? | May a write have been applied? | Safe to retry? | Client connection | Counter key | Chunk |\n")
	b.WriteString("| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |\n")
	for id := ErrRowID(0); id < ErrRowCount; id++ {
		r := ErrorRows[id]
		cells := []string{
			"`" + r.ID + "`", r.Situation, erowReplyCell(r), erowCode(r.Code), erowText(r.Message),
			r.Reached.String(), r.WriteApplied.String(), r.Retry, r.Conn.String(), "`" + r.CounterKey() + "`", strconv.Itoa(r.Chunk),
		}
		b.WriteString("| " + strings.Join(cells, " | ") + " |\n")
	}
	b.WriteString("\n\"Reached the database? no\" means no byte of the request was written to a database connection. The proxy's own retry may act only on rows where that column is \"no\".\n")
	return b.String()
}

func erowReplyCell(r ErrorRow) string {
	if s := r.Severity(); s != "" {
		return "`" + s + "` — " + r.Reply.String()
	}
	return r.Reply.String()
}

func erowCode(c string) string {
	if c == "" {
		return "—"
	}
	return "`" + c + "`"
}

func erowText(s string) string {
	if s == "" {
		return "—"
	}
	return strings.ReplaceAll(s, "|", "\\|")
}
