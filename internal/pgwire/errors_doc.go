package pgwire

import (
	"strconv"
	"strings"
)

// ErrorRowsMarkdown renders docs/error-contract.md directly from ErrorRows so
// the published error contract cannot drift from the wire builders.
func ErrorRowsMarkdown() string {
	var b strings.Builder
	b.WriteString("# Error contract\n\n")
	b.WriteString("Generated by `scripts/gen-docs.sh` from `internal/pgwire/errors.go` (the table `ErrorRows`). Do not edit by hand: a test fails when this file differs from the code.\n\n")
	b.WriteString("Every reply the proxy makes itself is an `ErrorResponse` with the severity, SQLSTATE and message below and a detail line `" + ReplyDetailPrefix + "<row id>`, followed by the end marker the row names. `ERROR` rows end with `ReadyForQuery` carrying the status byte the client believes (`I` outside a transaction; inside one, the current status). `FATAL` rows have no end marker and the client connection is closed. The extended-protocol row discards messages until `Sync` and then sends `ReadyForQuery`. Each proxy-made reply is counted under its counter key.\n\n")
	b.WriteString("| Row id | Situation | Reply | SQLSTATE | Message | Reached the database? | May a write have been applied? | Safe to retry? | Retried by the proxy? | Client connection | Counter key | Chunk |\n")
	b.WriteString("| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |\n")
	for id := ErrRowID(0); id < ErrRowCount; id++ {
		r := ErrorRows[id]
		cells := []string{
			"`" + r.ID + "`", r.Situation, erowReplyCell(r), erowCode(r.Code), erowText(r.Message),
			r.Reached.String(), r.WriteApplied.String(), r.Retry, id.ProxyRetry().String(), r.Conn.String(), "`" + r.CounterKey() + "`", strconv.Itoa(r.Chunk),
		}
		b.WriteString("| " + strings.Join(cells, " | ") + " |\n")
	}
	b.WriteString("\n\"Reached the database? no\" means no write of the request was attempted, or its first write was refused with zero bytes accepted (rule G8); once a write was handed to a database connection the request may have reached the database. The proxy's own retry (retry.policy pre-forward-once; off by default) reads that fact for the failure itself, never the row: it acts only on a failure where nothing reached the database. Such a failure outside a transaction is answered with `lost-after-read`, so that is the one row the proxy may retry; every other row is never retried by the proxy, whatever the policy. A retry runs at most once per request, re-enters the admission queue holding no connection, and its outcome is the client's one reply; when the policy declines, the client gets the row.\n")
	b.WriteString("\nThe choice between `lost-after-read` (08006, safe to retry) and `lost-after-write` (08007) rests on the classifier's safe shape (`SafeRead`, docs/safe-shape.md) and has the same limits: a view, a user-defined operator, a function shadowing an allow-listed name, or a table with a row-level security policy can hide a write behind a statement text that fits the safe shape. For such a statement the proxy may answer 08006 when a write happened; a database with such objects should treat 08006 like 08007.\n")
	return b.String()
}

func erowReplyCell(r ErrorRow) string {
	if s := r.Severity(); s != "" {
		return "`" + s + "` — " + r.Reply.String()
	}
	return r.Reply.String()
}

func erowCode(c string) string {
	if c == "" {
		return "—"
	}
	return "`" + c + "`"
}

func erowText(s string) string {
	if s == "" {
		return "—"
	}
	return strings.ReplaceAll(s, "|", "\\|")
}
