package pgwire

import "strings"

func RejectListMarkdown() string {
	var b strings.Builder
	b.WriteString("# Reject list and function allow-lists\n\n")
	b.WriteString("Generated by `scripts/gen-docs.sh` from `internal/pgwire/rejectlist.go`. Do not edit by hand: a test fails when this file differs from the code, and another test classifies every example below.\n\n")
	b.WriteString("A rejected statement is answered with `ERROR 0A000` (error row `unsupported-feature`) and nothing is sent to the database. A `Query` message is rejected as a whole when any statement in it is rejected. The classifier is a lexer, not a parser: a function, view, rule or default that hides one of these features is not seen.\n\n")
	b.WriteString("## Rejected\n\n| Reason | Feature | Why | Example |\n| --- | --- | --- | --- |\n")
	for _, r := range RejectRules {
		b.WriteString("| `" + r.Reason.String() + "` | " + rejCell(r.Feature) + " | " + rejCell(r.Why) + " | " + rejExample(r.Example) + " |\n")
	}
	b.WriteString("\n## Allowed because they are transaction-scoped\n\n| Form | Why | Example |\n| --- | --- | --- |\n")
	for _, f := range RejectAllowedForms {
		b.WriteString("| " + rejCell(f.Form) + " | " + rejCell(f.Why) + " | " + rejExample(f.Example) + " |\n")
	}
	b.WriteString("\n## Function allow-lists\n\n")
	b.WriteString("A statement is read-only-provable only if every function it calls (a name followed by `(`, with or without whitespace or comments between) is in this table, unqualified or qualified by `pg_catalog`. It is coalescable only if, in addition, every function it calls has \"yes\" in the coalescable column.\n\n")
	b.WriteString("| Function | Read-only-provable | Coalescable |\n| --- | --- | --- |\n")
	for _, e := range AllowList {
		co := "no"
		if e.Coalesce {
			co = "yes"
		}
		b.WriteString("| `" + e.Name + "` | yes | " + co + " |\n")
	}
	b.WriteString("\n## Words that end a proof\n\n")
	b.WriteString("Read-only-provable fails when any of these appears as an unquoted word anywhere in the statement: " + rejWords(rejWriteKeywords) + "; or `FOR` followed by " + rejWords(rejLockStrength) + " (a locking clause).\n\n")
	b.WriteString("Coalescable fails when any of these appears as an unquoted word: " + rejWords(rejPerCallKeywords) + ".\n\n")
	b.WriteString("Operators allowed in a read-only-provable statement: " + rejWords(rejOperators) + ".\n")
	return b.String()
}

func rejCell(s string) string { return strings.ReplaceAll(s, "|", "\\|") }

func rejExample(s string) string {
	if strings.HasPrefix(s, "(") {
		return s
	}
	return "`" + strings.ReplaceAll(s, "|", "\\|") + "`"
}

func rejWords(list []string) string {
	parts := make([]string, len(list))
	for i, w := range list {
		parts[i] = "`" + strings.ReplaceAll(w, "|", "\\|") + "`"
	}
	return strings.Join(parts, ", ")
}
