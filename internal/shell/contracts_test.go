var (
	updateContracts = flag.Bool("update-contracts", false, "rewrite docs/timeout-budget.md and docs/capacity-table.md")
	contractsOut    = flag.String("contracts-out", "", "write the generated contract documents into this folder")
)

func cell(s string) string { return strings.ReplaceAll(s, "|", `\|`) }

func TimeoutBudgetMarkdown() []byte {
	var b bytes.Buffer
	t := proxy.DefaultTimeouts()
	b.WriteString("# Timeout budget\n\n")
	b.WriteString("Generated by `scripts/gen-docs.sh` from `internal/proxy/contracts.go` and `internal/proxy/config.go`. Do not edit by hand: a test fails when this file differs from the code.\n\n")
	b.WriteString("Every wait the walking skeleton (chunk 6) has, with its initial value. Every value is initial and is tuned by a named experiment later (PLAN.md section 9.2). Config validation refuses a file whose waits do not nest (the second table).\n\n")
	b.WriteString("One rule holds for every deadline: time passes before the event. When an event arrives at time T, `Engine.Step` first fires every timer due at or before T, then processes the event, so a reply, a byte or a free connection that arrives at the very instant of its deadline is late and the deadline's outcome applies.\n\n")
	b.WriteString("| Wait | Where | Config key | Initial | What ends it |\n| --- | --- | --- | --- | --- |\n")
	for _, r := range proxy.TimeoutRows(t) {
		fmt.Fprintf(&b, "| %s | %s | `%s` | %s | %s |\n", cell(r.Wait), cell(r.Where), r.Key, r.Value, cell(r.Ends))
	}
	b.WriteString("\n## Nesting checked at config load\n\nAn inner wait must end before the outer one; `internal/config` refuses the file otherwise, naming the inner key.\n\n")
	b.WriteString("| Inner wait | Key | Initial | Outer wait | Key | Initial | Holds |\n| --- | --- | --- | --- | --- | --- | --- |\n")
	for _, n := range t.Nesting() {
		fmt.Fprintf(&b, "| %s | `%s` | %s | %s | `%s` | %s | %v |\n", n.Inner, n.InnerKey, n.InnerValue, n.Outer, n.OuterKey, n.OuterValue, n.InnerValue < n.OuterValue)
	}
	b.WriteString("\nNot yet built: client idle inside a transaction (chunk 7), cancel and clean-up of a dirty connection (chunk 7), coalesced flight (chunk 11), drain (chunk 13).\n")
	return b.Bytes()
}

func CapacityTableMarkdown() []byte {
	var b bytes.Buffer
	b.WriteString("# Capacity table\n\n")
	b.WriteString("Generated by `scripts/gen-docs.sh` from `internal/proxy/contracts.go` and `internal/shell/contracts.go`. Do not edit by hand: a test fails when this file differs from the code.\n\n")
	b.WriteString("One row per bounded thing in the walking skeleton (chunk 6), with its default. Config validation also checks that the gates in front of the connections are consistent: the queue holds at most one request per client (`queue.capacity` ≤ `limits.max_clients`), the clients in startup are at most the clients (`limits.max_startup` ≤ `limits.max_clients`), and the pool fits the fleet budget (`pool.connections` ≤ `fleet.backend_connections` / `fleet.instances`).\n\n")
	b.WriteString("| Bounded thing | Protects | Capacity | Config key | When full | Deadline | Gauge |\n| --- | --- | --- | --- | --- | --- | --- |\n")
	rows := append(proxy.CapacityRows(proxy.Config{}), CapacityRows()...)
	for _, r := range rows {
		fmt.Fprintf(&b, "| %s | %s | %s | `%s` | %s | `%s` | `%s` |\n", cell(r.Thing), cell(r.Protects), cell(r.Capacity), r.Key, cell(r.Full), r.Deadline, r.Gauge)
	}
	b.WriteString("\nNot yet built: per-tenant queues and active-tenant states (chunks 8, 9), coalescer flights, waiters and shared-reply bytes (chunk 11), concurrent cancels (chunk 7).\n")
	return b.Bytes()
}

func TestContractDocumentsAreGeneratedFromTheCode(t *testing.T) {
	docs := map[string][]byte{"timeout-budget.md": TimeoutBudgetMarkdown(), "capacity-table.md": CapacityTableMarkdown()}
	root := filepath.Join("..", "..", "docs")
	for name, want := range docs {
		switch {
		case *contractsOut != "":
			if err := os.WriteFile(filepath.Join(*contractsOut, name), want, 0o644); err != nil {
				t.Fatal(err)
			}
		case *updateContracts:
			if err := os.WriteFile(filepath.Join(root, name), want, 0o644); err != nil {
				t.Fatal(err)
			}
		default:
			got, err := os.ReadFile(filepath.Join(root, name))
			if err != nil || !bytes.Equal(got, want) {
				t.Fatalf("docs/%s is stale; run scripts/gen-docs.sh (%v)", name, err)
			}
		}
	}
}

func TestDefaultTimeoutsNest(t *testing.T) {
	if errs := proxy.DefaultTimeouts().Validate(); len(errs) != 0 {
		t.Fatal(errs)
	}
	for _, n := range proxy.DefaultTimeouts().Nesting() {
		if n.InnerValue >= n.OuterValue {
			t.Fatalf("%s does not end before %s", n.InnerKey, n.OuterKey)
		}
	}
}
